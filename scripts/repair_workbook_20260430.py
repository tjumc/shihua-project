def update_main_workbook() -> None:
    workbook = load_workbook(MAIN_WORKBOOK)
    # Sheet positions follow the current workbook template.
    rule_sheet = workbook.worksheets[3]
    final_sheet = workbook.worksheets[4]

    for row_number, new_name in RENAME_MAP.items():
        rule_sheet.cell(row_number, 2).value = new_name
        final_sheet.cell(row_number, 2).value = new_name

    for row_number, new_content in CLEAN_CONTENT.items():
        rule_sheet.cell(row_number, 9).value = new_content
        final_sheet.cell(row_number, 9).value = new_content

    for row_number, new_remark in FINAL_REMARKS.items():
        final_sheet.cell(row_number, 15).value = new_remark

    workbook.save(MAIN_WORKBOOK)
    workbook.close()


def update_audit_workbook(path: Path, worksheet_index: int) -> None:
    workbook = load_workbook(path)
    worksheet = workbook.worksheets[worksheet_index]
    # Audit workbooks only need synchronized rule names.
    for row_number, new_name in RENAME_MAP.items():
        worksheet.cell(row_number, 3).value = new_name
    workbook.save(path)
    workbook.close()


def main() -> None:
    update_main_workbook()
    update_audit_workbook(FINAL_AUDIT_WORKBOOK, worksheet_index=1)
    update_audit_workbook(ORIGINAL_AUDIT_WORKBOOK, worksheet_index=0)
    print("repair_complete")


if __name__ == "__main__":
    main()
